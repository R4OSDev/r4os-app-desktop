fn accented_glyph(base: u8, accent: u8, shift_base: bool) -> [u8; 8] {
    let source = ASCII[usize::from(base - b' ')];
    let mut result = [0; 8];
    result[0] = accent;
    for row in 1..8 {
        result[row] = source[if shift_base { row - 1 } else { row }];
    }
    result
}
fn cedilla_glyph(base: u8) -> [u8; 8] {
    let mut result = ASCII[usize::from(base - b' ')];
    result[7] = 0x30;
    result
}
#[cfg(test)]
mod tests {
    use super::*;
    use crate::render::content_hash::Blake3;
    #[test]
    fn current_original_zig_font_full_scalar_and_out_of_range_byte_oracle() {
        let mut hash = Blake3::new();
        for cp in 0..0x110000 {
            hash.update(&glyph_for_codepoint(cp));
        }
        for cp in [0x110000, 0x7fffffff, 0xffffffff] {
            hash.update(&glyph_for_codepoint(cp));
        }
        let expected = "17f5fdb48a140c58ef3ffd9cc8c75b9d4bef47f1c92677e31d5eff2f2ba080d5";
        let mut bytes = [0; 32];
        for (i, v) in bytes.iter_mut().enumerate() {
            *v = u8::from_str_radix(&expected[i * 2..i * 2 + 2], 16).unwrap();
        }
        assert_eq!(hash.finish(), bytes);
    }
}
