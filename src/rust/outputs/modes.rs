//! Retained consumer of the common R4GFX mode transaction. Native mode/BO,
//! rollback timers and cleanup stay with their original Library owner.
use super::topology_wire;
use crate::{
    render::output_geometry::topology::Output,
    runtime::library::{Context, required, result, scalar},
};
use alloc::vec::Vec;
use core::mem::{self, MaybeUninit};
use r4os_library_helpers::{Error, raw as c};
use r4os_sdk::{App, abi as a};
pub struct Modes {
    storage: Vec<MaybeUninit<c::R4GfxModeControlController>>,
    retired: bool,
}
impl Modes {
    pub fn new() -> Result<Self, Error> {
        let mut storage = Vec::new();
        storage
            .try_reserve_exact(1)
            .map_err(|_| Error::Native("Memory"))?;
        storage.push(MaybeUninit::uninit());
        required(unsafe { c::R4GfxModeControlController_create(storage[0].as_mut_ptr()) })?;
        Ok(Self {
            storage,
            retired: true,
        })
    }
    fn pointer(&self) -> *mut c::R4GfxModeControlController {
        self.storage.as_ptr().cast_mut().cast()
    }
    pub fn busy(&self) -> Result<bool, Error> {
        Ok(scalar(unsafe { c::R4GfxModeControlController_busy(0, self.pointer()) })? != 0)
    }
    pub fn error(&self) -> i32 {
        scalar(unsafe { c::R4GfxModeControlController_get_error_code(self.pointer()) })
            .map_or(a::gfx_output_error_invalid, |v| v as i32)
    }
    pub fn count(&self) -> usize {
        scalar(unsafe { c::R4GfxModeControlController_get_count(self.pointer()) })
            .map_or(0, |v| v as usize)
    }
    pub fn status(&self) -> Result<a::GfxModeStatus, Error> {
        let mut out = a::GfxModeStatus::default();
        required(unsafe {
            c::R4GfxModeControlController_get_status(
                self.pointer(),
                (&mut out as *mut a::GfxModeStatus).cast(),
            )
        })?;
        Ok(out)
    }
    pub fn reset(&mut self, context: &Context<'_, '_>) -> Result<bool, Error> {
        if self.busy()? || !self.cleanup(context)? {
            return Ok(false);
        }
        required(unsafe { c::R4GfxModeControlController_create(self.pointer()) })?;
        self.retired = true;
        Ok(true)
    }
    pub fn select(
        &mut self,
        context: &Context<'_, '_>,
        identity: a::GfxOutputId,
        choice: Output,
    ) -> Result<bool, Error> {
        let mut optional = unsafe { MaybeUninit::<c::R4LibrariesSlot>::zeroed().assume_init() };
        optional.flags = 1;
        optional.ptr = (&identity as *const a::GfxOutputId).cast_mut().cast();
        result(unsafe {
            c::R4GfxModeControlController_set_selected_output(self.pointer(), optional)
        })?;
        if scalar(unsafe { c::R4Media_modesRefresh(0, self.pointer(), context.draw()?) })? == 0 {
            return Ok(false);
        }
        let modes = self.modes()?;
        let count = self.count();
        if count > modes.len() {
            return Err(Error::InvalidProvider);
        }
        let selected = modes[..count].iter().position(|m| {
            m.width == choice.view.pixel_w
                && m.height == choice.view.pixel_h
                && m.refresh_millihz == choice.refresh_millihz
        });
        if let Some(index) = selected {
            result(unsafe {
                c::R4GfxModeControlController_set_selected(self.pointer(), index as u64)
            })?;
        }
        Ok(selected.is_some())
    }
    fn modes(&self) -> Result<[a::GfxOutputMode; a::gfx_output_max_modes as usize], Error> {
        // This getter projects the public canonical ABI array, not a private
        // Zig record. Its compiler-generated byte/align facts are exact.
        const {
            assert!(
                mem::size_of::<[a::GfxOutputMode; a::gfx_output_max_modes as usize]>()
                    == mem::size_of::<c::R4Lib_Value405>()
            );
            assert!(
                mem::align_of::<[a::GfxOutputMode; a::gfx_output_max_modes as usize]>()
                    == mem::align_of::<c::R4Lib_Value405>()
            );
        }
        let mut out = MaybeUninit::<[a::GfxOutputMode; a::gfx_output_max_modes as usize]>::uninit();
        required(unsafe {
            c::R4GfxModeControlController_get_modes(self.pointer(), out.as_mut_ptr().cast())
        })?;
        Ok(unsafe { out.assume_init() })
    }
    pub fn selected(&self) -> Result<a::GfxOutputMode, Error> {
        let index =
            scalar(unsafe { c::R4GfxModeControlController_get_selected(self.pointer()) })? as usize;
        if index >= self.count() || index >= a::gfx_output_max_modes as usize {
            return Err(Error::InvalidProvider);
        }
        Ok(self.modes()?[index])
    }
    pub fn apply(
        &mut self,
        app: &App<'_>,
        context: &Context<'_, '_>,
        signal: Option<a::GfxColorSignal>,
    ) -> Result<bool, Error> {
        let draw = context.draw()?;
        self.retired = false;
        let value = if let Some(signal) = signal {
            let mut colors = MaybeUninit::uninit();
            required(unsafe {
                c::R4Library_colorClient(0, app.start_context(), colors.as_mut_ptr())
            })?;
            scalar(unsafe {
                c::R4Media_modesApplyColor(
                    0,
                    self.pointer(),
                    draw,
                    colors.as_ptr(),
                    (&signal as *const a::GfxColorSignal).cast(),
                )
            })?
        } else {
            scalar(unsafe { c::R4Media_modesApply(0, self.pointer(), draw) })?
        };
        Ok(value != 0)
    }
    pub fn poll(&mut self, context: &Context<'_, '_>) -> Result<bool, Error> {
        Ok(scalar(unsafe { c::R4Media_modesPoll(0, self.pointer(), context.draw()?) })? != 0)
    }
    pub fn resolve(&mut self, context: &Context<'_, '_>, keep: bool) -> Result<bool, Error> {
        Ok(scalar(unsafe {
            c::R4Media_modesResolve(0, self.pointer(), context.draw()?, keep as u8)
        })? != 0)
    }
    pub fn cleanup(&mut self, context: &Context<'_, '_>) -> Result<bool, Error> {
        let done =
            scalar(unsafe { c::R4Media_modesCleanup(0, self.pointer(), context.draw()?) })? != 0;
        if done && !self.busy()? {
            self.retired = true;
        }
        Ok(done)
    }
    pub fn close(&mut self, context: &Context<'_, '_>) -> Result<bool, Error> {
        result(unsafe { c::R4Media_modesClose(0, self.pointer(), context.draw()?) })?;
        let _ = self.poll(context)?;
        Ok(self.cleanup(context)? && !self.busy()?)
    }
}
impl Drop for Modes {
    fn drop(&mut self) {
        if !self.retired {
            mem::forget(mem::take(&mut self.storage));
        }
    }
}
pub fn same_timing(left: Output, right: Output) -> Result<bool, Error> {
    let left = topology_wire::output(left)?;
    let right = topology_wire::output(right)?;
    Ok(scalar(unsafe { c::R4GfxModeControl_sameTiming(0, &left, &right) })? != 0)
}
pub struct Restoration {
    native: c::R4GfxModeControlRestoration,
}
impl Restoration {
    pub fn new() -> Result<Self, Error> {
        let mut out = MaybeUninit::uninit();
        required(unsafe { c::R4GfxModeControlRestoration_create(out.as_mut_ptr()) })?;
        Ok(Self {
            native: unsafe { out.assume_init() },
        })
    }
    pub fn seen(&self, choice: Output, identity: a::GfxOutputId) -> Result<bool, Error> {
        let choice = topology_wire::output(choice)?;
        Ok(scalar(unsafe {
            c::R4GfxModeControlRestoration_seen(
                0,
                &self.native,
                &choice,
                (&identity as *const a::GfxOutputId).cast(),
            )
        })? != 0)
    }
    pub fn record(&mut self, choice: Output, identity: a::GfxOutputId) -> Result<(), Error> {
        let choice = topology_wire::output(choice)?;
        result(unsafe {
            c::R4GfxModeControlRestoration_record(
                0,
                &mut self.native,
                &choice,
                (&identity as *const a::GfxOutputId).cast(),
            )
        })?;
        Ok(())
    }
}
